'use strict';
// Recorder code-injection hardening: a codegen recording is untrusted text; nothing from it may reach generated JS as code.
const test = require('node:test');
const assert = require('node:assert/strict');
const rec = require('../lib/recorder');

const MARK = /pwned|child_process|evil/;

/** Convert a recording and prove the output is one parseable program in which no attacker text survived outside literals/comments. */
function convertSafely(body, opts = {}) {
  const text = `const { chromium } = require('playwright');\n(async () => {\n  const page = await context.newPage();\n${body}\n  // ---------------------\n  await context.close();\n})();\n`;
  const out = rec.convert(text, { name: 'automation-x', now: '2026-01-01T00:00:00Z', ...opts });
  const code = out.files['main.js'];
  assert.doesNotThrow(() => new Function('require', 'process', '__dirname', code), 'generated main.js must still parse');
  const bad = code.search(/[\r\u2028\u2029]/);
  assert.ok(bad < 0, `stray line terminator near: ${JSON.stringify(code.slice(Math.max(0, bad - 120), bad + 40))}`);
  const masked = rec.mask(code);
  assert.ok(!MARK.test(masked), `attacker text leaked into executable code:\n${code}`);
  return { out, code };
}

test('commentText strips line terminators and comment delimiters', () => {
  const t = rec.commentText('a\r\nb\u2028c\u2029d*/e/*f**//**//g');
  assert.ok(!/[\r\n\u2028\u2029]/.test(t) && !t.includes('*/') && !t.includes('/*'), t);
  assert.equal(rec.commentText('x'.repeat(500)).length, 203);
});

test('jsStr always yields a single inert token', () => {
  for (const s of ["a'b", 'a\\b', 'a\nb', 'a\rb', 'a\u2028b', 'a\u2029b', '</script>', '`${x}`', '\u0000\u001f\u007f']) {
    const lit = rec.jsStr(s);
    assert.doesNotThrow(() => new Function(`return ${lit};`), JSON.stringify(s));
    assert.equal(new Function(`return ${lit};`)(), s);
    assert.ok(!/[\r\n\u2028\u2029<]/.test(lit), JSON.stringify(lit));
    assert.equal(rec.unquote(lit), s);
  }
});

test('comment breakout via escaped newline in a locator string stays in a comment', () => {
  const { code } = convertSafely("  await page.getByText('x\\nglobalThis.__pwned=1;//').click();\n  await page.getByText('y\\r\\u2028globalThis.__pwned=2').click();");
  assert.ok(code.includes('// step 1: click'));
});

test('comment breakout via */ in url, assertion and unknown statements', () => {
  const { code } = convertSafely("  await expect(page.locator('h1')).toContainText('*/ globalThis.__pwned=1; /*');\n  evil.call('*/ child_process /*');\n  await page.goto('https://a.example/');",
    { url: 'https://a.example/*/ globalThis.__pwned=1;/*\nglobalThis.__pwned=2' });
  assert.ok(code.includes('GENERATED by amx-record'));
});

test('real newlines / U+2028 inside an unknown statement cannot escape its TODO comment', () => {
  convertSafely("  foo(`a\nglobalThis.__pwned=1\u2028globalThis.__pwned=2\rchild_process`);");
});

test('goto: only literal http/https URLs are emitted, and via a string literal', () => {
  const bad = ["javascript:globalThis.__pwned=1", 'data:text/html,evil', 'file:///c:/evil', 'ftp://evil/x', 'about:blank'];
  for (const u of bad) {
    const { out } = convertSafely(`  await page.goto('${u}');\n  await page.goto('https://ok.example/');`);
    assert.ok(out.files['main.js'].includes('TODO(unconverted)'), u);
    assert.ok(!out.steps.some((s) => s[2] === u), u);
    assert.equal(out.params.find((p) => p.name === 'start_url').default, 'https://ok.example/', 'a rejected goto must not become start_url');
  }
  const creds = convertSafely("  await page.goto('https://user:pw@evil.example/');");
  assert.ok(creds.code.includes('TODO(unconverted)'));
  const tpl = convertSafely('  await page.goto(`https://a.example/${globalThis.__pwned = 1}`);');
  if (!tpl.code.includes('TODO(unconverted)')) throw new Error(tpl.code);
  const concat = convertSafely("  await page.goto('https://a.example/');\n  await page.goto('https://a.example/' + globalThis.__pwned);");
  assert.ok(concat.code.includes('TODO(unconverted)'));
  const second = convertSafely("  await page.goto('https://a.example/');\n  await page.goto('https://b.example/x\\'y');");
  assert.ok(second.code.includes("page.goto('https://b.example/x\\'y', { waitUntil: 'domcontentloaded' })"), second.code);
});

test('option arguments: non-literal or non-allow-listed objects are dropped with a TODO, the action is kept', () => {
  const cases = [
    "{ timeout: require('child_process').execSync('evil') }",
    '{ force: true, __proto__: { evil: 1 } }',
    '{ evilKey: 1 }',
    '{ timeout: 1 + globalThis.__pwned }',
    '{ button: `right${globalThis.__pwned}` }',
    '{ timeout: (() => { globalThis.__pwned = 1; })() }',
    '{ modifiers: ["Evil"] }',
  ];
  for (const opt of cases) {
    const { code, out } = convertSafely(`  await page.getByRole('button', { name: 'Go' }).click(${opt});`);
    assert.ok(code.includes('rp.click((p) => p.getByRole(\'button\', { name: \'Go\' }));'), `${opt}\n${code}`);
    assert.ok(code.includes('TODO(unconverted): options dropped'), opt);
    assert.ok(out.warnings.some((w) => /options were not a strict literal/.test(w)), opt);
  }
  const ok = convertSafely("  await page.getByRole('button', { name: 'Go' }).click({ button: 'right', clickCount: 2, delay: 5, modifiers: ['Shift'], position: { x: 1, y: 2 }, force: true });");
  assert.ok(ok.code.includes("{ button: 'right', clickCount: 2, delay: 5, modifiers: ['Shift'], position: { x: 1, y: 2 }, force: true }"), ok.code);
});

test('value-carrying calls with non-literal arguments become TODOs (never executed)', () => {
  for (const call of ["fill(globalThis.__pwned = 1)", "fill('a' + globalThis.__pwned)", "press(require('child_process'))", "selectOption({ value: globalThis.__pwned })", "dragTo(page.locator('evil'))", "fill('a', { timeout: evil() })"]) {
    const { code } = convertSafely(`  await page.locator('#a').${call};`);
    assert.ok(code.includes('TODO(unconverted)'), call);
  }
});

test('locator chains: calls, identifiers, operators and regex/quote tricks are rejected; plain codegen locators survive unchanged', () => {
  const evil = [
    "page.locator('a').filter({ hasText: require('child_process') }).click()",
    "page.locator('a').filter({ has: page.locator(globalThis.__pwned) }).click()",
    "page.getByText(/ \"/ + globalThis.__pwned + \"/).click()",
    "page.getByRole('button', { name: evil() }).click()",
    "page.locator('a').nth(globalThis.__pwned).click()",
    "page.locator('a').evaluate(globalThis.__pwned).click()",
    "page.locator(globalThis.__pwned).click()",
    "page.click(globalThis.__pwned)",
    "page.click('#a' + globalThis.__pwned)",
    'page.locator(`a${globalThis.__pwned}`).click()',
  ];
  for (const e of evil) {
    const { code } = convertSafely(`  await ${e};`);
    assert.ok(code.includes('TODO(unconverted)'), e);
  }
  const good = convertSafely("  await page.getByRole('row', { name: /INV-\\d+/i, exact: true }).getByText('a;b').first().nth(2).click();\n  await page.locator('input[name=\"q\"]').fill('hello');\n  await page.frameLocator('#f').getByLabel('L').click();");
  assert.ok(good.code.includes("p.getByRole('row', { name: /INV-\\d+/i, exact: true }).getByText('a;b').first().nth(2)"), good.code);
  assert.ok(good.code.includes("p.locator('input[name=\"q\"]')"), good.code);
  assert.ok(good.code.includes("p.frameLocator('#f').getByLabel('L')"), good.code);
});

test('template literals / </script> / backticks in values are emitted as escaped single-quoted strings', () => {
  const { code } = convertSafely("  await page.getByLabel('Note').fill('</script><script>x</script> `${1}`');");
  assert.ok(!code.includes('</script>'));
  assert.ok(code.includes('\\u003c/script>'), code);
});

test('page variables: unknown or reserved names never reach generated code', () => {
  for (const pv of ['require', 'process', 'framework', 'w', 'foo']) {
    const { code } = convertSafely(`  await ${pv}.locator('#a').click();`);
    assert.ok(code.includes('TODO(unconverted)'), pv);
  }
  const { code } = convertSafely("  const process = await processPromise;\n  const page1Promise = foo.waitForEvent('popup');");
  assert.ok(!/const process\b/.test(rec.mask(code)), code);
  assert.ok(code.includes('TODO(unconverted)'));
});

test('sleep / waitForURL / waitForLoadState arguments are re-validated', () => {
  const { code } = convertSafely("  await page.waitForTimeout(globalThis.__pwned);\n  await page.waitForURL(globalThis.__pwned);\n  await page.waitForLoadState(globalThis.__pwned);\n  await page.waitForURL('**/done', { timeout: 5000 });\n  await page.waitForLoadState('networkidle');");
  assert.equal((code.match(/TODO\(unconverted\)/g) || []).length, 3);
  assert.ok(code.includes("page.waitForURL('**/done', { timeout: 5000 })"));
  assert.ok(code.includes("page.waitForLoadState('networkidle')"));
});

test('parseLiteralArgs accepts the codegen grammar and nothing else', () => {
  assert.equal(rec.emitLiteral(rec.parseLiteralArgs("'a', { name: /x/i, exact: true }", { regex: true })[1]), '{ name: /x/i, exact: true }');
  for (const bad of ['a', 'x()', "'a' + 'b'", '`a`', '{ [k]: 1 }', '{ a: 1 }', '{ name: x }', '/x/', "'a\nb'", "'\\u{1F600}'", '1e999', '[[[[[[1]]]]]]', 'undefined', '-x']) {
    assert.equal(rec.parseLiteralArgs(bad), null, bad);
  }
  assert.equal(rec.parseLiteralArgs('/a"b/', { regex: true }), null);
  assert.equal(rec.parseLiteralArgs('/*x*/', { regex: true }), null);
  assert.equal(rec.parseLiteralArgs('x'.repeat(5000)), null);
});

test('amx-record: the recorded URL is validated as http(s) and cannot carry control characters into the header', () => {
  const rc = require('../bin/amx-record');
  assert.throws(() => rc.parseArgs(['http://a.example/\nglobalThis.__pwned=1', '--name', 'automation-x']), /URL/);
  assert.throws(() => rc.parseArgs(['javascript:alert(1)', '--name', 'automation-x']), /http/);
  assert.equal(rc.parseArgs(['https://ok.example/p?q=1', '--name', 'automation-x']).url, 'https://ok.example/p?q=1');
});
