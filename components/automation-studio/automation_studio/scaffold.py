"""AUTOSTATION Studio — scaffold bridge.

Converts the contract step's project_yaml dict into real files by writing
a project.yaml and delegating to tools/scaffold.py (the same path that
``python tools/amx.py scaffold`` uses).  Keeps Studio decoupled from the
scaffolder's internals while staying in sync automatically.

Usage:
    from automation_studio.scaffold import scaffold_from_contract, ScaffoldResult
    result = scaffold_from_contract(contract["project_yaml"], Path("~/projects").expanduser())
    if result.success:
        print(f"Scaffolded at {result.out_path}")
"""
from __future__ import annotations

import subprocess
import sys
import tempfile
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

# Path to tools/scaffold.py — walk up from this file: scaffold.py → automation_studio
# → automation-studio → components → <root> → tools/
_STUDIO_DIR = Path(__file__).resolve().parent.parent   # components/automation-studio
_ROOT = _STUDIO_DIR.parent.parent                       # repo root
_SCAFFOLD_TOOL = _ROOT / "tools" / "scaffold.py"

# Fields accepted by tools/scaffold.py (project.yaml schema)
_SCAFFOLD_FIELDS = {
    "name", "description", "owner", "classification",
    "owner_team", "runtime", "version", "timeout_s", "register",
}


@dataclass
class ScaffoldResult:
    success: bool
    out_path: Path
    output: str                    # combined stdout from the scaffolder
    error: str = ""                # stderr or error message on failure


def _write_project_yaml(proj: dict[str, Any], dest: Path) -> None:
    """Write a flat project.yaml from the contract dict.

    Uses simple ``key: value`` lines so the stdlib fallback in scaffold.py
    works even when PyYAML is not installed.
    """
    lines = ["# project.yaml — generated by AUTOSTATION Studio\n"]
    for key in ("name", "description", "owner", "classification", "owner_team",
                "runtime", "version", "timeout_s"):
        val = proj.get(key)
        if val is None:
            continue
        # Quote strings that contain special YAML characters
        v = str(val)
        if any(c in v for c in (':', '#', "'", '"', '\n')) or not v:
            v = '"' + v.replace('"', "'") + '"'
        lines.append(f"{key}: {v}\n")
    dest.write_text("".join(lines), encoding="utf-8")


def scaffold_from_contract(
    project_yaml: dict[str, Any],
    out_base: Path,
    *,
    no_verify: bool = True,
    register: str | None = None,
) -> ScaffoldResult:
    """Scaffold an automation project from the contract's project_yaml dict.

    Args:
        project_yaml:  The ``project_yaml`` dict from a CONTRACT step result.
        out_base:      Parent directory; the automation folder is created inside it.
        no_verify:     Skip running pytest on the generated project (default True;
                       the developer runs tests after customising selectors etc.).
        register:      Optional path to a manifest.yaml to register the automation.

    Returns:
        ScaffoldResult with success, out_path, output, and error.
    """
    if not _SCAFFOLD_TOOL.exists():
        return ScaffoldResult(
            success=False,
            out_path=out_base,
            output="",
            error=f"scaffold tool not found at {_SCAFFOLD_TOOL}",
        )

    name = str(project_yaml.get("name", "automation-unnamed"))
    out_path = (out_base / name).resolve()

    # Merge in register key if provided
    proj = {k: v for k, v in project_yaml.items() if k in _SCAFFOLD_FIELDS}
    if register:
        proj["register"] = register

    with tempfile.TemporaryDirectory(prefix="autostation-studio-") as tmp:
        yaml_path = Path(tmp) / "project.yaml"
        _write_project_yaml(proj, yaml_path)

        cmd: list[str] = [sys.executable, str(_SCAFFOLD_TOOL), str(yaml_path),
                          "--out", str(out_path)]
        if no_verify:
            cmd.append("--no-verify")

        try:
            proc = subprocess.run(
                cmd,
                cwd=str(_ROOT),
                capture_output=True,
                text=True,
                timeout=120,
            )
            output = (proc.stdout or "").strip()
            stderr = (proc.stderr or "").strip()
            combined = "\n".join(filter(None, [output, stderr]))

            if proc.returncode == 0:
                return ScaffoldResult(success=True, out_path=out_path, output=combined)
            else:
                return ScaffoldResult(success=False, out_path=out_path, output=combined,
                                      error=stderr or f"scaffold exited {proc.returncode}")

        except subprocess.TimeoutExpired:
            return ScaffoldResult(success=False, out_path=out_path, output="",
                                  error="scaffold timed out after 120 s")
        except Exception as exc:  # noqa: BLE001
            return ScaffoldResult(success=False, out_path=out_path, output="",
                                  error=str(exc))
