"""AUTOSTATION Studio — scaffold bridge.

Converts the contract step's project_yaml dict into real files by writing
a project.yaml and delegating to tools/scaffold.py (the same path that
``python tools/amx.py scaffold`` uses).  Keeps Studio decoupled from the
scaffolder's internals while staying in sync automatically.

Usage:
    from automation_studio.scaffold import scaffold_from_contract, ScaffoldResult
    result = scaffold_from_contract(contract["project_yaml"], Path("~/projects").expanduser())
    if result.success:
        print(f"Scaffolded at {result.out_path}")
"""
from __future__ import annotations

import subprocess
import sys
import tempfile
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

# Path to tools/scaffold.py — walk up from this file: scaffold.py → automation_studio
# → automation-studio → components → <root> → tools/
_STUDIO_DIR = Path(__file__).resolve().parent.parent   # components/automation-studio
_ROOT = _STUDIO_DIR.parent.parent                       # repo root
_SCAFFOLD_TOOL = _ROOT / "tools" / "scaffold.py"

if str(_ROOT / "tools") not in sys.path:
    sys.path.insert(0, str(_ROOT / "tools"))
import project_fields as pf  # noqa: E402  (the one validator/emitter shared with tools/scaffold.py)

# Fields the CONTRACT may set. `register` is deliberately not one of them: it makes the scaffolder run the registry CLI against a path,
# and the contract is LLM-written text. Registration is only possible through the explicit `register=` argument of scaffold_from_contract.
_SCAFFOLD_FIELDS = {
    "name", "description", "owner", "classification",
    "owner_team", "runtime", "version", "timeout_s",
}


@dataclass
class ScaffoldResult:
    success: bool
    out_path: Path
    output: str                    # combined stdout from the scaffolder
    error: str = ""                # stderr or error message on failure


def _validated(proj: dict[str, Any]) -> dict[str, Any]:
    """Validate every contract field (raises project_fields.FieldError). Optional fields keep their scaffolder defaults when absent."""
    out: dict[str, Any] = {
        "name": pf.check_name(proj.get("name")),
        "description": pf.check_description(proj.get("description")),
        "owner": pf.check_owner(proj.get("owner")),
        "classification": pf.check_classification(proj.get("classification")),
    }
    if proj.get("owner_team") is not None:
        out["owner_team"] = pf.check_team(proj["owner_team"])
    if proj.get("runtime") is not None:
        out["runtime"] = pf.check_runtime(proj["runtime"])
    if proj.get("version") is not None:
        out["version"] = pf.check_version(proj["version"])
    if proj.get("timeout_s") is not None:
        out["timeout_s"] = pf.check_timeout(proj["timeout_s"])
    if proj.get("register") is not None:
        out["register"] = pf.check_register(proj["register"])
    return out


def _write_project_yaml(proj: dict[str, Any], dest: Path) -> None:
    """Write a flat project.yaml from the contract dict with the safe emitter (values are JSON-quoted when they are not simple words, so a
    newline, quote or colon in a value cannot add keys or break the file). Fields are validated first: raises project_fields.FieldError."""
    checked = _validated({**proj, "name": proj.get("name", "automation-unnamed")} if "name" in proj else proj)
    text = pf.emit_flat_yaml(checked, order=("name", "description", "owner", "classification", "owner_team", "runtime", "version",
                                             "timeout_s", "register"),
                             header="# project.yaml - generated by AUTOSTATION Studio")
    dest.write_text(text, encoding="utf-8")


def scaffold_from_contract(
    project_yaml: dict[str, Any],
    out_base: Path,
    *,
    no_verify: bool = False,
    register: str | None = None,
) -> ScaffoldResult:
    """Scaffold an automation project from the contract's project_yaml dict.

    Args:
        project_yaml:  The ``project_yaml`` dict from a CONTRACT step result.
        out_base:      Parent directory; the automation folder is created inside it.
        no_verify:     Skip running pytest on the generated project (default False: the
                       generated project's own tests run, so a template or contract bug is
                       caught instead of silently shipped).
        register:      Optional path to a manifest.yaml to register the automation.

    Returns:
        ScaffoldResult with success, out_path, output, and error.
    """
    if not _SCAFFOLD_TOOL.exists():
        return ScaffoldResult(
            success=False,
            out_path=out_base,
            output="",
            error=f"scaffold tool not found at {_SCAFFOLD_TOOL}",
        )

    try:
        name = pf.check_name(project_yaml.get("name", "automation-unnamed"))
    except pf.FieldError as exc:
        return ScaffoldResult(success=False, out_path=out_base, output="", error=f"invalid contract: {exc}")
    out_path = (out_base / name).resolve()

    # Merge in register key if provided
    proj = {k: v for k, v in project_yaml.items() if k in _SCAFFOLD_FIELDS}
    if register:
        proj["register"] = register

    with tempfile.TemporaryDirectory(prefix="autostation-studio-") as tmp:
        yaml_path = Path(tmp) / "project.yaml"
        try:
            _write_project_yaml(proj, yaml_path)
        except pf.FieldError as exc:
            return ScaffoldResult(success=False, out_path=out_path, output="", error=f"invalid contract: {exc}")

        cmd: list[str] = [sys.executable, str(_SCAFFOLD_TOOL), str(yaml_path),
                          "--out", str(out_path)]
        if no_verify:
            cmd.append("--no-verify")

        try:
            proc = subprocess.run(
                cmd,
                cwd=str(_ROOT),
                capture_output=True,
                text=True,
                timeout=120,
            )
            output = (proc.stdout or "").strip()
            stderr = (proc.stderr or "").strip()
            combined = "\n".join(filter(None, [output, stderr]))

            if proc.returncode == 0:
                return ScaffoldResult(success=True, out_path=out_path, output=combined)
            else:
                return ScaffoldResult(success=False, out_path=out_path, output=combined,
                                      error=stderr or f"scaffold exited {proc.returncode}")

        except subprocess.TimeoutExpired:
            return ScaffoldResult(success=False, out_path=out_path, output="",
                                  error="scaffold timed out after 120 s")
        except Exception as exc:  # noqa: BLE001
            return ScaffoldResult(success=False, out_path=out_path, output="",
                                  error=str(exc))
