"""Manifest / triggers / history file IO. Every write is validated first and is deterministic (byte-stable)."""
from __future__ import annotations

import json
import os
import re
import tempfile
from dataclasses import dataclass, field
from datetime import datetime, timezone
from pathlib import Path

from wrapper_core import manifest as wc_manifest
from wrapper_core import miniyaml

PLACEHOLDER_SHA = "0" * 64
HISTORY_DIR = "history"
HISTORY_FILE = "CHANGELOG.md"
TRIGGERS_FILE = "triggers.json"


class ValidationFailed(Exception):
    def __init__(self, errors: list[str]):
        super().__init__("manifest is invalid:\n  - " + "\n  - ".join(errors))
        self.errors = errors


def today() -> str:
    """UTC date; ``REGISTRY_TODAY`` pins it for tests and reproducible CI."""
    return os.environ.get("REGISTRY_TODAY") or datetime.now(timezone.utc).strftime("%Y-%m-%d")


def now_iso() -> str:
    return os.environ.get("REGISTRY_NOW") or datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def atomic_write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=str(path.parent), prefix=path.name + ".", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def load_manifest(path: Path | str) -> dict:
    try:
        return wc_manifest.parse(Path(path).read_text(encoding="utf-8"))
    except FileNotFoundError:
        raise SystemExit(f"error: manifest not found: {path}")
    except wc_manifest.ManifestError as exc:
        raise SystemExit(f"error: {exc}")


def dump_manifest(m: dict) -> str:
    return miniyaml.dumps(m)


def save_manifest(path: Path | str, m: dict, *, allow_placeholders: bool = False, artifacts_dir: Path | None = None) -> None:
    """Validate then write. Refuses to persist an invalid manifest."""
    from .checks import validate_all
    report = validate_all(m, allow_placeholders=allow_placeholders, artifacts_dir=artifacts_dir)
    if report.errors:
        raise ValidationFailed(report.errors)
    atomic_write(Path(path), dump_manifest(m))


# ---- triggers.json ---------------------------------------------------------------------------------
def load_triggers(path: Path) -> dict:
    try:
        doc = json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, ValueError):
        doc = {}
    if isinstance(doc, list):
        doc = {"triggers": doc}
    doc.setdefault("schema_version", 1)
    doc.setdefault("triggers", [])
    return doc


def load_triggers_text(text: str) -> dict:
    try:
        doc = json.loads(text)
    except ValueError:
        doc = {}
    if isinstance(doc, list):
        doc = {"triggers": doc}
    doc.setdefault("schema_version", 1)
    doc.setdefault("triggers", [])
    return doc


def save_triggers(path: Path, doc: dict) -> None:
    atomic_write(Path(path), json.dumps(doc, indent=2, sort_keys=True) + "\n")


# ---- history (CHANGELOG-style) -----------------------------------------------------------------------
_LINE = re.compile(r"^- (\d{4}-\d{2}-\d{2}) `([a-z-]+)` \*\*([^*]+)\*\* - (.*)$")


def history_path(manifest_path: Path) -> Path:
    return Path(manifest_path).parent / HISTORY_DIR / HISTORY_FILE


HISTORY_HEADER = ("# Registry history\n\nOne line per operator action, newest at the bottom. Generated by "
                  "`python -m registry`; the merge request is the approval record.\n\n")


def render_history(existing: str | None, action: str, target: str, detail: str, actor: str | None = None) -> str:
    """Pure: the history file text after appending one line."""
    text = existing if existing else HISTORY_HEADER
    detail = re.sub(r"\s+", " ", detail).strip()
    line = f"- {today()} `{action}` **{target}** - {detail}" + (f" (by {actor})" if actor else "")
    if not text.endswith("\n"):
        text += "\n"
    return text + line + "\n"


def append_history(manifest_path: Path, action: str, target: str, detail: str, actor: str | None = None) -> None:
    p = history_path(manifest_path)
    existing = p.read_text(encoding="utf-8") if p.exists() else None
    atomic_write(p, render_history(existing, action, target, detail, actor))


def read_history(manifest_path: Path) -> list[dict]:
    p = history_path(manifest_path)
    out = []
    if p.exists():
        for line in p.read_text(encoding="utf-8").splitlines():
            m = _LINE.match(line)
            if m:
                out.append({"date": m.group(1), "action": m.group(2), "target": m.group(3), "detail": m.group(4)})
    return out
